import type { MetadataRoute } from "next";

import { industrySlugs } from "@/lib/industries";
import { INSIGHT_SUMMARY_DATE, insights, isInsightIndexable } from "@/lib/insights/posts";
import { guides, PILLAR_SLUG } from "@/lib/guides/guides";
import LASTMOD from "@/lib/seo/lastmod.json";

const SITE = "https://intelmadesimple.com";

type Entry = {
  path: string;
  priority: number;
  changeFrequency: MetadataRoute.Sitemap[number]["changeFrequency"];
  lastModified: string;
};

// Every date is a real per-page change date, never the build time. Static pages read
// lib/seo/lastmod.json, regenerated by lib/seo/gen-lastmod.mjs from the last git commit date,
// or the file's modified date when it has uncommitted changes. Guides use their own `modified`
// field and insight summaries use the date they were written. Insight summaries under the word
// threshold are noindex, so they are left out. /api and /dev are excluded in robots.ts.
const GUIDES_UPDATED = guides.map((g) => g.modified).sort().at(-1) ?? INSIGHT_SUMMARY_DATE;

const mod = (path: string): string => {
  const date = (LASTMOD as Record<string, string | undefined>)[path];
  if (!date) throw new Error(`No lastmod date for ${path}. Run: node lib/seo/gen-lastmod.mjs`);
  return date;
};

const SERVICES: { slug: string; priority: number }[] = [
  { slug: "ai-readiness-audit", priority: 0.9 },
  { slug: "enquiry-desk", priority: 0.9 },
  { slug: "team-enablement", priority: 0.9 },
  { slug: "ai-automation", priority: 0.85 },
  { slug: "seo", priority: 0.85 },
  { slug: "custom-software", priority: 0.85 },
  { slug: "strategic-advisory", priority: 0.85 },
];

const ENTRIES: Entry[] = [
  { path: "/", priority: 1.0, changeFrequency: "weekly", lastModified: mod("/") },
  { path: "/about", priority: 0.8, changeFrequency: "monthly", lastModified: mod("/about") },
  { path: "/services", priority: 0.9, changeFrequency: "monthly", lastModified: mod("/services") },
  ...SERVICES.map(
    (s): Entry => ({
      path: `/services/${s.slug}`,
      priority: s.priority,
      changeFrequency: "monthly",
      lastModified: mod(`/services/${s.slug}`),
    }),
  ),
  { path: "/process", priority: 0.75, changeFrequency: "monthly", lastModified: mod("/process") },
  { path: "/case-studies", priority: 0.8, changeFrequency: "monthly", lastModified: mod("/case-studies") },
  { path: "/reviews", priority: 0.7, changeFrequency: "monthly", lastModified: mod("/reviews") },
  { path: "/pricing", priority: 0.85, changeFrequency: "monthly", lastModified: mod("/pricing") },
  { path: "/guides", priority: 0.8, changeFrequency: "monthly", lastModified: GUIDES_UPDATED },
  { path: "/insights", priority: 0.6, changeFrequency: "weekly", lastModified: mod("/insights") },
  { path: "/solutions", priority: 0.9, changeFrequency: "monthly", lastModified: mod("/solutions") },
  { path: "/faq", priority: 0.7, changeFrequency: "monthly", lastModified: mod("/faq") },
  { path: "/contact", priority: 0.9, changeFrequency: "monthly", lastModified: mod("/contact") },
  { path: "/privacy", priority: 0.4, changeFrequency: "yearly", lastModified: mod("/privacy") },
  { path: "/terms", priority: 0.4, changeFrequency: "yearly", lastModified: mod("/terms") },
  { path: "/ai-policy", priority: 0.65, changeFrequency: "yearly", lastModified: mod("/ai-policy") },
  { path: "/industries", priority: 0.9, changeFrequency: "monthly", lastModified: mod("/industries") },
  ...industrySlugs.map(
    (slug): Entry => ({
      path: `/industries/${slug}`,
      priority: 0.85,
      changeFrequency: "monthly",
      lastModified: mod(`/industries/${slug}`),
    }),
  ),
  ...guides.map(
    (g): Entry => ({
      path: `/guides/${g.slug}`,
      priority: g.slug === PILLAR_SLUG ? 0.85 : 0.75,
      changeFrequency: "monthly",
      lastModified: g.modified,
    }),
  ),
  ...insights.filter(isInsightIndexable).map(
    (p): Entry => ({
      path: `/insights/${p.slug}`,
      priority: 0.6,
      changeFrequency: "yearly",
      lastModified: INSIGHT_SUMMARY_DATE,
    }),
  ),
];

export default function sitemap(): MetadataRoute.Sitemap {
  return ENTRIES.map((e) => ({
    url: e.path === "/" ? `${SITE}/` : `${SITE}${e.path}`,
    lastModified: new Date(e.lastModified),
    changeFrequency: e.changeFrequency,
    priority: e.priority,
  }));
}
